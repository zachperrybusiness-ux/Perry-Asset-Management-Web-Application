/* ============================================================================
   Perry Asset Management — Daily AI Report tab  (app-aiadvisor.js)
   Added 2026-07-26.  Load after app-consolidate.js.

   Renders the nightly buy/sell/hold brief generated by the worker
   (cloudflare-worker/worker-advisor.js). The worker assembles the portfolio
   and the warehouse's FRED / internals / fundamentals data, has Claude write
   the narrative, and caches the result — so this tab is a fast read of a
   pre-computed report, with an on-demand "Regenerate" that hits the same
   endpoint. All numbers in the report come from the site's own data layer;
   the model provides wording and prioritization only.
   ============================================================================ */

(function () {
  'use strict';

  var WORKER = (typeof WORKER_URL !== 'undefined' && WORKER_URL)
    ? WORKER_URL
    : 'https://perry-finance-proxy.zachperrybusiness.workers.dev';

  function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c];
    });
  }
  function el(id) { return document.getElementById(id); }

  var ACTION_STYLE = {
    BUY:  { bg: '#2E7D52', label: 'BUY' },
    ADD:  { bg: '#2E7D52', label: 'ADD' },
    HOLD: { bg: '#5A6A7A', label: 'HOLD' },
    TRIM: { bg: '#8B6914', label: 'TRIM' },
    SELL: { bg: '#8B2A2A', label: 'SELL' }
  };
  var STANCE_COLOR = { 'Risk-On': '#2E7D52', 'Neutral': '#8B6914', 'Defensive': '#8B2A2A' };

  function chip(action) {
    var s = ACTION_STYLE[action] || ACTION_STYLE.HOLD;
    return '<span style="display:inline-block;background:' + s.bg + ';color:#FFFFFF;font-size:11px;font-weight:700;'
      + 'padding:3px 12px;border-radius:12px;letter-spacing:.5px;font-family:Arial,Helvetica,sans-serif;">' + s.label + '</span>';
  }
  function convChip(c) {
    var col = c === 'High' ? '#003C71' : c === 'Medium' ? '#5B9BD5' : '#A8C8E8';
    return '<span style="display:inline-block;background:' + col + ';color:#FFFFFF;font-size:10px;font-weight:600;'
      + 'padding:2px 9px;border-radius:10px;font-family:Arial,Helvetica,sans-serif;">' + esc(c || '—') + '</span>';
  }

  function fmtWhen(iso) {
    if (!iso) return '—';
    try {
      var d = new Date(iso);
      var ageH = (Date.now() - d.getTime()) / 36e5;
      var age = ageH < 1 ? Math.round(ageH * 60) + ' min ago' : ageH < 30 ? ageH.toFixed(1) + ' h ago' : Math.round(ageH / 24) + ' d ago';
      return d.toLocaleString() + ' (' + age + ')';
    } catch (e) { return iso; }
  }

  function render(data) {
    var root = el('aiBriefRoot');
    if (!root) return;

    if (!data || (data.error && !data.report)) {
      var msg = data && data.error === 'no_report'
        ? 'No report has been generated yet. The worker generates one automatically every morning at ~3:00am ET — or generate the first one now.'
        : 'Report unavailable: ' + esc(data && (data.message || data.error) || 'unknown error');
      root.innerHTML =
        '<div class="card"><div class="card-title">Daily AI Report</div>'
        + '<div class="card-body" style="text-align:center;padding:34px;">'
        + '<div style="font-size:13px;color:var(--text-sec);max-width:520px;margin:0 auto 16px;line-height:1.6;">' + msg + '</div>'
        + '<button class="btn" onclick="aiBriefGenerate(true)">⚡ Generate First Report</button>'
        + '<div id="aiBriefGenStatus" style="margin-top:10px;font-size:12px;color:var(--text-sec);"></div>'
        + '</div></div>';
      return;
    }

    var r = data.report || {};
    var cs = data.context_summary || {};
    var stanceCol = STANCE_COLOR[(r.posture || {}).stance] || '#5A6A7A';

    var h = '';

    // ── Masthead banner ──
    h += '<div style="background:var(--navy);color:#FFFFFF;border-radius:6px;padding:18px 22px;margin-bottom:14px;font-family:Arial,Helvetica,sans-serif;">'
      + '<div style="display:flex;justify-content:space-between;align-items:flex-start;gap:14px;flex-wrap:wrap;">'
      + '<div style="flex:1;min-width:260px;">'
      + '<div style="font-size:10px;text-transform:uppercase;letter-spacing:1px;opacity:.75;">Daily AI Advisor Report</div>'
      + '<div style="font-size:19px;font-weight:800;line-height:1.35;margin:4px 0 6px;">' + esc(r.headline || data.headline || '—') + '</div>'
      + '<div style="font-size:11px;opacity:.75;">Generated ' + fmtWhen(data.generated_at)
      + (cs.total_value ? ' · portfolio $' + Number(cs.total_value).toLocaleString() : '')
      + (cs.n_positions ? ' · ' + cs.n_positions + ' positions' : '')
      + (cs.cash_pct != null ? ' · ' + cs.cash_pct + '% cash' : '') + '</div>'
      + '</div>'
      + '<div style="text-align:center;min-width:130px;">'
      + '<div style="font-size:10px;text-transform:uppercase;letter-spacing:.8px;opacity:.75;">Stance</div>'
      + '<div style="font-size:22px;font-weight:800;color:' + stanceCol + ';background:#FFFFFF;border-radius:5px;padding:6px 14px;margin-top:4px;">' + esc((r.posture || {}).stance || '—') + '</div>'
      + '</div>'
      + '<div style="display:flex;flex-direction:column;gap:6px;">'
      + '<button class="btn" style="white-space:nowrap;" onclick="aiBriefGenerate(true)">🔄 Regenerate Now</button>'
      + '<div id="aiBriefGenStatus" style="font-size:11px;opacity:.8;max-width:170px;"></div>'
      + '</div>'
      + '</div>'
      + ((r.posture || {}).summary ? '<div style="font-size:12.5px;line-height:1.6;margin-top:10px;border-top:1px solid rgba(255,255,255,.25);padding-top:10px;">' + esc(r.posture.summary) + '</div>' : '')
      + '</div>';

    // ── Macro context: one paragraph + the numbers behind it ──
    var mac = r.macro || {};
    var macroPara = mac.paragraph || r.macro_context;   // tolerate old cached reports
    if (macroPara) {
      h += '<div class="card" style="margin-bottom:14px;"><div class="card-title">Macro Snapshot — What the Data Says Today</div>'
        + '<div class="card-body">'
        + '<div style="font-size:13px;line-height:1.7;margin-bottom:' + ((mac.bullets || []).length ? '12px' : '0') + ';">' + esc(macroPara) + '</div>'
        + ((mac.bullets || []).length
            ? '<div style="display:grid;grid-template-columns:repeat(auto-fit,minmax(250px,1fr));gap:6px 18px;background:#F4F6F9;border:1px solid #D0D7E0;border-radius:5px;padding:10px 14px;">'
              + mac.bullets.map(function (b) {
                  return '<div style="font-size:12px;color:#000000;line-height:1.5;">&bull; ' + esc(b) + '</div>';
                }).join('')
              + '</div>'
            : '')
        + '</div>'
        + '<div class="card-sources"><strong>Sources:</strong><br>&bull; FRED&reg; macro series, market internals and daily signals from the site\'s nightly warehouse ingest &bull; Narrative generated by ' + esc(data.model || 'PAM-1, the site\'s own on-worker advisor model') + ' — no external AI APIs.</div></div>';
    }

    // ── Per-portfolio summaries (one card row per active account) ──
    var pfs = r.portfolios || [];
    if (pfs.length) {
      h += '<div class="card" style="margin-bottom:14px;">'
        + '<div class="card-title">Your Portfolios — ' + pfs.length + ' Active</div>'
        + '<div class="card-body" style="display:grid;grid-template-columns:repeat(auto-fit,minmax(290px,1fr));gap:12px;">'
        + pfs.map(function (p) {
            var secStr = Object.entries(p.sector_mix || {}).map(function (kv) { return esc(kv[0]) + ' ' + kv[1] + '%'; }).join(' · ');
            return '<div style="border:1px solid #D0D7E0;border-radius:6px;overflow:hidden;">'
              + '<div style="background:#003C71;color:#FFFFFF;padding:8px 14px;display:flex;justify-content:space-between;align-items:center;gap:8px;">'
              + '<span style="font-size:13px;font-weight:700;">' + esc(p.name) + '</span>'
              + '<span style="font-size:12px;font-weight:600;">$' + Number(p.value).toLocaleString() + '</span></div>'
              + '<div style="padding:10px 14px;font-size:12.5px;line-height:1.6;color:#000000;">' + esc(p.summary) + '</div>'
              + (secStr ? '<div style="padding:0 14px 10px;font-size:10.5px;color:#5A6A7A;">' + secStr + '</div>' : '')
              + '</div>';
          }).join('')
        + '</div>'
        + '<div class="card-sources"><strong>Method:</strong> derived from your holdings rows grouped by account on every run — any portfolio you add appears here automatically on the next report.</div></div>';
    }

    // ── Recommendations: only the relevant calls ──
    var recs = r.recommendations || [];
    if (recs.length) {
      var KIND_META = {
        sector_gap:        { label: 'UNDERWEIGHT', col: '#2E7D52' },
        sector_overweight: { label: 'OVERWEIGHT',  col: '#8B6914' },
        concentration:     { label: 'CONCENTRATION', col: '#8B2A2A' },
        position:          { label: 'POSITION',    col: '#003C71' },
        cash:              { label: 'CASH',        col: '#5B9BD5' },
        data:              { label: 'DATA',        col: '#5A6A7A' }
      };
      h += '<div class="card" style="margin-bottom:14px;">'
        + '<div class="card-title">What Actually Matters Today — ' + recs.length + ' Recommendation' + (recs.length > 1 ? 's' : '') + '</div>'
        + '<div class="card-body" style="font-size:12.5px;">'
        + recs.map(function (rec) {
            var km = KIND_META[rec.kind] || KIND_META.position;
            return '<div style="display:flex;gap:12px;align-items:flex-start;padding:10px 12px;margin-bottom:8px;background:#F4F6F9;border-left:4px solid ' + km.col + ';border-radius:0 5px 5px 0;">'
              + '<span style="flex-shrink:0;background:' + km.col + ';color:#FFFFFF;font-size:9.5px;font-weight:700;letter-spacing:.5px;padding:3px 9px;border-radius:10px;margin-top:1px;">' + km.label + '</span>'
              + '<span style="line-height:1.6;color:#000000;">' + esc(rec.text) + '</span>'
              + '</div>';
          }).join('')
        + '</div>'
        + '<div class="card-sources"><strong>Method:</strong> sector weights compared to the SPY baseline (gaps &gt; 5pp flagged, with a liquid sector ETF and its top constituents named); concentration vs institutional single-name limits; only the top-scored position calls surface — never a verdict on every line item.</div></div>';
    }

    // ── Risks ──
    var risks = r.risks || [];
    if (risks.length) {
      h += '<div class="card" style="margin-bottom:14px;"><div class="card-title">Risks to Watch</div><div class="card-body" style="font-size:12.5px;">'
        + risks.map(function (f) {
            return '<div style="padding:8px 12px;margin-bottom:7px;background:rgba(139,42,42,0.06);border-left:4px solid #8B2A2A;border-radius:0 4px 4px 0;line-height:1.55;">' + esc(f) + '</div>';
          }).join('') + '</div></div>';
    }

    // ── Disclaimer ──
    h += '<div style="font-size:11px;color:var(--text-sec);padding:10px 14px;background:#F4F6F9;border:1px solid #D0D7E0;border-radius:5px;line-height:1.6;">'
      + esc(r.disclaimer || 'Automated analysis generated from your portfolio and public market data. Not individualized investment advice; verify before acting.')
      + ' A fresh report is generated automatically every morning (~3:00am ET) after the nightly data ingest.</div>';

    root.innerHTML = h;
  }

  function load(force) {
    var root = el('aiBriefRoot');
    if (root && !root.getAttribute('data-loaded')) {
      root.innerHTML = '<div style="text-align:center;padding:40px;color:var(--text-sec);"><span class="spinner"></span> Loading daily AI report…</div>';
    }
    fetch(WORKER + '/advisor-report')
      .then(function (r) { return r.json(); })
      .then(function (d) { if (root) root.setAttribute('data-loaded', '1'); render(d); })
      .catch(function (e) { render({ error: 'network', message: e.message }); });
  }

  window.aiBriefOnShow = function () {
    var root = el('aiBriefRoot');
    // Refresh at most every 5 minutes on tab open.
    var last = root ? +(root.getAttribute('data-at') || 0) : 0;
    if (Date.now() - last < 5 * 60 * 1000) return;
    if (root) root.setAttribute('data-at', String(Date.now()));
    load(false);
  };

  window.aiBriefGenerate = function (force) {
    var st = el('aiBriefGenStatus');
    if (st) st.innerHTML = '<span class="spinner"></span> Generating — PAM-1 is scoring the book against today\'s data…';
    fetch(WORKER + '/advisor-report/generate' + (force ? '?force=1' : ''), { method: 'POST' })
      .then(function (r) { return r.json(); })
      .then(function (d) {
        if (d.error) { if (st) st.textContent = 'Failed: ' + d.error; return; }
        if (d.skipped) { if (st) st.textContent = 'Skipped: ' + (d.reason || 'cooldown'); if (d.report) load(); return; }
        if (st) st.textContent = 'Done — refreshing…';
        setTimeout(load, 600);
      })
      .catch(function (e) { if (st) st.textContent = 'Failed: ' + e.message; });
  };
})();
